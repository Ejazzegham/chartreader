import type { Candle } from './markets';
import { yahooOnly, yahooCarriesVolume } from './fallback';

// =====================================================================================
// REAL MARKET VOLUME for VSA.
// Deriv candles (forex, metals, synthetic indices) carry NO volume at all. VSA needs volume, so it is attached here
// from a market that really trades the same thing:
//   crypto  (Binance pairs, and Deriv's BTC / ETH / LTC / BNB / XRP)  -> Binance spot volume (real traded volume)
//   forex majors, gold, silver, oil (WTI / Brent), DXY                  -> CME / COMEX / NYMEX / ICE FUTURES volume (exchange volume, the standard
//                                                                          volume proxy for spot forex, because spot forex has no central tape)
//   crosses (EUR/JPY, GBP/JPY, EUR/GBP ...)                              -> no contract of their own: the volume of the TWO currency futures that make
//                                                                          the cross (EUR + JPY futures), labelled as a proxy. Deriv tick volume (M1 - H1) as the other source.
//   Deriv synthetic indices (Volatility, Boom, Crash, Step, Jump)       -> NO volume exists
//                                                                          (synthetics are generated by an algorithm, there is no market behind them)
// Where no real volume exists VSA does not guess: it shows the read but gives NO signal and NO entry.
// Pure maths, no imports from the app, so the server scanner uses the same rules.
// =====================================================================================

export type VolSource = { kind: 'binance'; raw: string; label: string } | { kind: 'yahoo'; y: string; y2?: string; proxy?: boolean; label: string } | null;

// Futures that track each spot pair (Yahoo symbols of the CME / ICE contracts)
const FUT: Record<string, [string, string]> = {
  frxEURUSD: ['6E=F', 'CME EUR futures'], frxGBPUSD: ['6B=F', 'CME GBP futures'], frxUSDJPY: ['6J=F', 'CME JPY futures'],
  frxAUDUSD: ['6A=F', 'CME AUD futures'], frxUSDCAD: ['6C=F', 'CME CAD futures'], frxUSDCHF: ['6S=F', 'CME CHF futures'],
  frxNZDUSD: ['6N=F', 'CME NZD futures'], frxXAUUSD: ['GC=F', 'COMEX gold futures'], frxXAGUSD: ['SI=F', 'COMEX silver futures'],
  frxDXY: ['DX=F', 'ICE US Dollar Index futures'],
};
// Oil: Deriv / broker names differ (Brent, WTI, "Oil/USD", XTI, XBR), so they are matched by pattern instead of one fixed id.
const OIL: [RegExp, string, string][] = [
  [/^frx(BRO|BRENT|XBR|UKO)/i, 'BZ=F', 'ICE Brent crude futures'],
  [/^frx(WTI|XTI|USO|CL|OIL)/i, 'CL=F', 'NYMEX WTI crude futures'],
];
const futFor = (id: string): [string, string] | undefined => FUT[id] ?? OIL.find(([re]) => re.test(id))?.slice(1) as [string, string] | undefined;
// Currency futures at CME: a cross has none of its own, but both of its currencies do (USD has no contract of its own to add).
const LEG: Record<string, [string, string]> = { EUR: ['6E=F', 'EUR'], GBP: ['6B=F', 'GBP'], JPY: ['6J=F', 'JPY'], AUD: ['6A=F', 'AUD'], CAD: ['6C=F', 'CAD'], CHF: ['6S=F', 'CHF'], NZD: ['6N=F', 'NZD'] };
export function crossLegs(id: string): { y: string; y2: string; label: string } | undefined {
  const m = /^frx([A-Z]{3})([A-Z]{3})$/.exec(id), a = m && LEG[m[1]], b = m && LEG[m[2]];
  return a && b ? { y: a[0], y2: b[0], label: `${a[1]} + ${b[1]} futures volume (cross proxy: this cross has no contract of its own)` } : undefined;
}
const CRY: Record<string, string> = { cryBTCUSD: 'BTCUSDT', cryETHUSD: 'ETHUSDT', cryLTCUSD: 'LTCUSDT', cryBNBUSD: 'BNBUSDT', cryXRPUSD: 'XRPUSDT' };

export function volumeSource(id: string): VolSource {
  if (/^bn[A-Z0-9]{5,20}$/.test(id)) return { kind: 'binance', raw: id.slice(2), label: 'Binance spot volume' }; // those candles already carry v
  if (CRY[id]) return { kind: 'binance', raw: CRY[id], label: 'Binance spot volume' };
  const fut = futFor(id);
  if (fut) return { kind: 'yahoo', y: fut[0], label: fut[1] };
  const cr = crossLegs(id);
  if (cr) return { kind: 'yahoo', y: cr.y, y2: cr.y2, proxy: true, label: cr.label };
  return null;
}
// Does the candle feed of this symbol already include volume (Binance pairs and the oil futures do)?
export const feedHasVolume = (id: string) => /^bn[A-Z0-9]{5,20}$/.test(id) || yahooCarriesVolume(id);

export function noVolumeReason(id: string): string {
  if (/^(R_|1HZ|BOOM|CRASH|stpRNG|JD|RDBEAR|RDBULL|WLD|cry|frx|OTC)/.test(id) && !volumeSource(id)) {
    return /^frx/.test(id) ? 'This pair has no futures contract (and none for its two currencies), so it has no exchange volume.' : 'Synthetic indices are generated by an algorithm, so there is no real market volume.';
  }
  return 'This market has no real volume feed.';
}

// ---- Deriv TICK volume: the number of price updates inside each candle ----
// This is the volume MetaTrader shows for spot forex / gold / silver / oil, and the one most retail VSA is done on. It comes from the same
// Deriv feed as the candles, so it needs no second website and works for the crosses that have no futures contract. It is a count of
// price changes, NOT traded lots, so it is always labelled "tick volume". Counting ticks costs one request per 5000 ticks, so it is
// limited to M1 - H1 (the pages are read newest first and shown while they load); synthetic indices tick at a fixed rate, so their tick count
// says nothing and they get none. DXY and oil are not on Deriv at all, so they have no ticks to count.
export const TICK_MAX_GRAN = 3600;
export const tickVolOk = (id: string, gran: number) => /^frx/.test(id) && !yahooOnly(id) && gran > 0 && gran <= TICK_MAX_GRAN;
// Tick times (epoch seconds, any order) -> one bar per candle with the number of ticks inside it. The oldest candle is dropped because the
// ticks before the first one received are unknown, so its count would be short. Candles with no tick at all get no bar (never invented).
export function tickBarsFrom(times: number[], gran: number): Candle[] {
  if (!times.length || gran <= 0) return [];
  let oldest = Infinity;
  for (const x of times) if (x < oldest) oldest = x;
  const firstFull = Math.floor(oldest / gran) * gran + gran, m = new Map<number, number>();
  for (const x of times) { const b = Math.floor(x / gran) * gran; if (b >= firstFull) m.set(b, (m.get(b) ?? 0) + 1); }
  return [...m.entries()].sort((p, q) => p[0] - q[0]).map(([t, v]) => ({ t, o: 0, h: 0, l: 0, c: 0, v }));
}
export const TICK_LABEL = 'Deriv tick volume (price updates per candle, the volume MT5 shows for forex)';
export type VolUsed = 'futures' | 'ticks';
const volUsed = new Map<string, VolUsed>();
export const setVolUsed = (id: string, gran: number, u: VolUsed) => { volUsed.set(`${id}:${gran}`, u); };
export const getVolUsed = (id: string, gran: number): VolUsed | undefined => volUsed.get(`${id}:${gran}`);
// Name of the volume that the VSA is really reading for this market + timeframe
export function volLabel(id: string, gran: number): string {
  const src = volumeSource(id), u = getVolUsed(id, gran);
  return u === 'ticks' || (!src && tickVolOk(id, gran)) ? TICK_LABEL : src?.label ?? '';
}
// Can this market get any volume at all (futures / exchange / tick)?
export const hasVolumePath = (id: string, gran: number) => !!volumeSource(id) || tickVolOk(id, gran);

// ---- Why does a market show "no volume"? Loading, feed failed, too few candles with trades, or no source at all. ----
// The feed (volumeFeed.ts) reports its state here per symbol + granularity; the VSA screen turns it into a message.
export type VolState = 'loading' | 'ok' | 'failed';
const volState = new Map<string, VolState>();
export const setVolState = (id: string, gran: number, s: VolState) => { volState.set(`${id}:${gran}`, s); };
export const getVolState = (id: string, gran: number): VolState | undefined => volState.get(`${id}:${gran}`);
export const setTickState = (id: string, gran: number, s: VolState) => { volState.set(`${id}:${gran}:t`, s); };
export const getTickState = (id: string, gran: number): VolState | undefined => volState.get(`${id}:${gran}:t`);
// VSA runs when at least this share of the last 40 candles carries a traded volume (and 2 of the newest 3 do). A futures market has a daily
// break and quiet minutes where spot keeps trading, so some candles have none; those are skipped by VSA, never guessed.
export const VSA_MIN_COVER = 0.7;
// How many of the last 40 candles carry a traded volume
export const volCover = (c: Candle[]) => { const w = c.slice(-40); return { have: w.filter((x) => (x.v ?? 0) > 0).length, of: w.length }; };
// Short word for the "Volume feed" tile while VSA has no volume yet
export function volTile(id: string, gran: number): 'Loading...' | 'Feed error' | 'Too little volume' {
  const src = volumeSource(id), tk = tickVolOk(id, gran);
  const f = src ? (feedHasVolume(id) ? 'ok' : getVolState(id, gran)) : undefined, t = tk ? getTickState(id, gran) : undefined;
  if ((!src || f === 'failed') && (!tk || t === 'failed')) return 'Feed error';
  return f === 'ok' || t === 'ok' ? 'Too little volume' : 'Loading...';
}

export function volMissingNote(id: string, gran: number, c: Candle[]): string {
  const src = volumeSource(id), tk = tickVolOk(id, gran);
  if (!src && !tk) {
    return /^frx/.test(id) && !yahooOnly(id) && gran > TICK_MAX_GRAN
      ? 'This pair has no futures contract, and tick volume only works on M1 to H1 (above that there are too many ticks to count). Switch to H1 or lower.'
      : noVolumeReason(id);
  }
  const cv = volCover(c), fst: VolState | undefined = feedHasVolume(id) ? 'ok' : getVolState(id, gran), tst = getTickState(id, gran);
  const fut = !src ? '' : fst === 'failed' ? `The real volume feed (${src.label}) did not answer: no volume data came back (no internet / VPN, or that futures market is closed). The app keeps retrying every few seconds.`
    : fst !== 'ok' ? `Loading real volume (${src.label}) ...`
    : `${src.label} is loaded, but only ${cv.have} of the last ${cv.of} candles have traded volume (that futures market is closed or very quiet at these hours).`;
  const tick = !tk ? '' : tst === 'failed' ? 'Deriv tick volume could not be loaded (connection busy, or the market is closed); retrying.'
    : tst !== 'ok' ? 'Loading Deriv tick volume ...' : `Tick volume is loaded but only ${cv.have} of the last ${cv.of} candles have it yet.`;
  return `${[fut, tick].filter(Boolean).join(' ')} VSA needs volume on at least ${Math.round(VSA_MIN_COVER * 100)}% of the last 40 candles, including the newest ones.`;
}

// Put volume on candles. `vol` = candles of the volume source (any granularity that divides `gran`, usually 1 minute or the same).
// A candle gets the SUM of the volume bars that start inside it. Candles with no matching bar are left without volume (never invented).
export function attachVolume(c: Candle[], vol: Candle[], gran: number): Candle[] {
  if (!c.length || !vol.length || gran <= 0) return c;
  const sum = new Map<number, number>();
  for (const x of vol) {
    if (!(x.v !== undefined && x.v > 0)) continue;
    const k = Math.floor(x.t / gran) * gran;
    sum.set(k, (sum.get(k) ?? 0) + x.v);
  }
  return c.map((x) => { const v = sum.get(Math.floor(x.t / gran) * gran); return v !== undefined ? { ...x, v } : x; });
}

// Candles that are still being drawn. The last candle is "forming" while the clock has not reached its end.
export const granOf = (c: Candle[]): number => {
  const d: number[] = [];
  for (let i = Math.max(1, c.length - 20); i < c.length; i++) { const g = c[i].t - c[i - 1].t; if (g > 0) d.push(g); }
  if (!d.length) return 0;
  d.sort((p, q) => p - q);
  return d[Math.floor(d.length / 2)];
};
export const isForming = (c: Candle[], nowMs: number): boolean => {
  if (c.length < 2) return false;
  const g = granOf(c), last = c[c.length - 1];
  return g > 0 && nowMs / 1000 < last.t + g && nowMs / 1000 >= last.t;
};
// Closed candles only: the forming candle is dropped. Its volume is partial and its close can still change, so signals read from it repaint.
export const closedCandles = (c: Candle[], nowMs: number): Candle[] => (isForming(c, nowMs) ? c.slice(0, -1) : c);

// ---- volume pane (TradingView style) helpers ----
// 12 345 -> "12.3K", 4 200 000 -> "4.2M". Small numbers stay whole.
export function fmtVol(v: number): string {
  if (!isFinite(v) || v <= 0) return '0';
  const a = Math.abs(v);
  return a >= 1e9 ? `${(v / 1e9).toFixed(2)}B` : a >= 1e6 ? `${(v / 1e6).toFixed(2)}M` : a >= 1e3 ? `${(v / 1e3).toFixed(a >= 1e5 ? 0 : 1)}K` : String(Math.round(v));
}
// Moving average of volume over the last `n` candles that HAVE volume (a gap does not drag the line to zero). NaN until `min` bars were seen.
export function volMA(c: Candle[], n = 20, min = 5): number[] {
  return c.map((_, i) => {
    let s = 0, k = 0;
    for (let j = i; j >= 0 && j > i - n; j--) { const v = c[j].v ?? 0; if (v > 0) { s += v; k++; } }
    return k >= min ? s / k : NaN;
  });
}
// What the empty volume pane says. '' when the candles carry volume (nothing to explain).
export function volPaneNote(id: string | undefined, gran: number, c: Candle[]): string {
  if (!id || c.slice(-40).some((x) => (x.v ?? 0) > 0)) return '';
  if (!hasVolumePath(id, gran)) return /^(R_|1HZ|BOOM|CRASH|stpRNG|JD|RDBEAR|RDBULL|WLD)/.test(id) ? 'No volume: synthetic index' : 'No volume feed for this market';
  const t = volTile(id, gran);
  return t === 'Loading...' ? 'Loading volume...' : t === 'Feed error' ? 'Volume feed not answering, retrying' : 'Volume too thin to show';
}
